"""Classify hand MOVEMENTS (swipe left/right/up/down) with the DollarPy recogniser.

DollarPy implements the $P point-cloud recogniser: it compares the *shape* of a
cloud of points and ignores the order they were drawn in. A raw swipe left and a
raw swipe right are therefore the same cloud (a horizontal line). To keep the
direction, each movement is encoded as two curves against time before matching:

    band 1 (bottom):  x = time 0..1,  y = 1.5 + horizontal travel  (-1..1)
    band 2 (top):     x = time 0..1,  y = 4.5 + vertical travel    (-1..1)

A right swipe is a rising line in band 1 and a flat line in band 2; a down swipe
is flat in band 1 and rising in band 2, and so on. Each direction becomes a
clearly different shape, which DollarPy classifies against stored templates.

Templates live in swipe_templates.json. Defaults are generated by
tools/make_swipe_templates.py; tools/record_swipe_templates.py adds real ones
recorded from the camera.
"""

import json
import math
from pathlib import Path

from dollarpy import Point, Recognizer, Template

TEMPLATES_FILE = Path(__file__).with_name("swipe_templates.json")
DIRECTIONS = {"SWIPE_LEFT": "left", "SWIPE_RIGHT": "right", "SWIPE_UP": "up", "SWIPE_DOWN": "down"}
RESAMPLE_POINTS = 24      # points per gesture inside DollarPy (fewer = faster)
MIN_SCORE = 0.70          # DollarPy score (0..1) needed to accept a movement


def encode(trail):
    """trail: [(t, x, y), ...] palm positions in camera-frame units.

    Returns [[px, py], ...] in the two-band time encoding described above, or
    None when the trail is too short or does not move.
    """
    if len(trail) < 3:
        return None
    t0, x0, y0 = trail[0]
    duration = trail[-1][0] - t0
    travel = max(max(abs(x - x0), abs(y - y0)) for _, x, y in trail)
    if duration <= 0 or travel <= 1e-6:
        return None
    horizontal = [[(t - t0) / duration, 1.5 + (x - x0) / travel] for t, x, _ in trail]
    vertical = [[(t - t0) / duration, 4.5 + (y - y0) / travel] for t, _, y in trail]
    return horizontal + vertical[::-1]   # one continuous path: band 1, then band 2 back


def load_templates(path=TEMPLATES_FILE):
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    return {name: points for name, points in data.items() if any(name.startswith(d) for d in DIRECTIONS)}


class MovementClassifier:
    """Wraps DollarPy so the library's in-place edits never touch our templates."""

    def __init__(self, templates=None, min_score=MIN_SCORE):
        self.templates = load_templates() if templates is None else templates
        self.min_score = min_score
        self.last = None   # (name, score) of the most recent recognition, for the UI

    @staticmethod
    def _label(name):
        return next((d for d in DIRECTIONS if name.startswith(d)), None)

    def classify(self, trail):
        """Return (direction, gesture_name, score); direction is None when rejected."""
        encoded = encode(trail)
        if encoded is None or not self.templates:
            return None, None, 0.0
        # dollarpy's _resample inserts points into the lists it is given, so it
        # always receives fresh copies (otherwise templates grow on every call).
        templates = [Template(name, [Point(x, y) for x, y in points]) for name, points in self.templates.items()]
        try:
            name, score = Recognizer(templates).recognize([Point(x, y) for x, y in encoded], n=RESAMPLE_POINTS)
        except (IndexError, ZeroDivisionError):
            return None, None, 0.0
        label = self._label(name) if name else None
        self.last = (label, score)
        if label is None or score < self.min_score:
            return None, label, score
        return DIRECTIONS[label], label, score


def synthetic_trail(direction, samples=12, duration=0.35, drift=0.0, curve=0.0, easing="linear", distance=0.25):
    """A clean movement used for default templates and tests."""
    ux, uy = {"left": (-1, 0), "right": (1, 0), "up": (0, -1), "down": (0, 1)}[direction]
    trail = []
    for i in range(samples):
        u = i / (samples - 1)
        s = {"linear": u, "ease": (1 - math.cos(math.pi * u)) / 2, "fast_start": math.sin(u * math.pi / 2)}[easing]
        side = drift * u + curve * math.sin(math.pi * u)
        x = .5 + distance * (ux * s + uy * side)
        y = .5 + distance * (uy * s + ux * side)
        trail.append((u * duration, x, y))
    return trail
